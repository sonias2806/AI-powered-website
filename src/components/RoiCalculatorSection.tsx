import React, { useState, useId } from 'react';
import {
  TrendingUp,
  Calculator,
  MessageSquare,
  Sparkles,
  Zap,
  CheckCircle2,
  ArrowRight,
  ShieldAlert,
  Percent
} from 'lucide-react';
import { CONTACT_INFO } from '../data/siteData';

